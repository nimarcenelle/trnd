/** A character limit becomes the word limit the workspace counts in, at about six characters a word. */
export const wordLimit = (p: Prompt) =>
  p.limit === null
    ? null
    : p.unit === "words"
      ? p.limit
      : Math.max(50, Math.round(p.limit / 6));
